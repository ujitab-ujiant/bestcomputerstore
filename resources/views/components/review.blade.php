<script>
document.addEventListener('DOMContentLoaded', function() {
    const reviewSlider = document.querySelector('.review-slider');

    function changeSlide(slideId, dotGroup) {
        let slides;
        if (dotGroup === 'desktop-dot') {
            slides = document.querySelectorAll('.review-slide-desktop');
        } else if (dotGroup === 'tablet-dot') {
            slides = document.querySelectorAll('.review-slide-tablet');
        } else {
            slides = document.querySelectorAll('.review-slide-mobile');
        }

        slides.forEach(slide => {
            slide.classList.add('opacity-0', 'pointer-events-none');
            slide.classList.remove('opacity-100');
        });

        const targetSlide = document.getElementById(slideId);
        if (targetSlide) {
            targetSlide.classList.remove('opacity-0', 'pointer-events-none');
            targetSlide.classList.add('opacity-100');

            updateContainerHeight(targetSlide);
        }

        const dots = document.querySelectorAll(`.${dotGroup}`);
        dots.forEach(dot => {
            dot.classList.remove('bg-green-600');
            dot.classList.add('bg-gray-300');
        });

        const activeDot = document.querySelector(`.${dotGroup}[data-slide="${slideId}"]`);
        if (activeDot) {
            activeDot.classList.remove('bg-gray-300');
            activeDot.classList.add('bg-green-600');
        }
    }

    function updateContainerHeight(activeSlide) {
        if (activeSlide) {
            const slideHeight = activeSlide.scrollHeight;
            reviewSlider.style.height = `${slideHeight}px`;
        }
    }

    document.querySelectorAll('.pagination-dot').forEach(dot => {
        dot.addEventListener('click', function() {
            const slideId = this.getAttribute('data-slide');
            const dotClass = this.classList.contains('desktop-dot') ? 'desktop-dot' : 
                             this.classList.contains('tablet-dot') ? 'tablet-dot' : 'mobile-dot';
            changeSlide(slideId, dotClass);
        });
    });

    function setContainerHeight() {
        let activeSlide;
        if (window.innerWidth >= 1024) { 
            activeSlide = document.querySelector('.review-slide-desktop.opacity-100');
            if (!activeSlide) {
                changeSlide('desktop-slide1', 'desktop-dot');
                activeSlide = document.getElementById('desktop-slide1');
            }
        } else if (window.innerWidth >= 768) { 
            activeSlide = document.querySelector('.review-slide-tablet.opacity-100');
            if (!activeSlide) {
                changeSlide('tablet-slide1', 'tablet-dot');
                activeSlide = document.getElementById('tablet-slide1');
            }
        } else { 
            activeSlide = document.querySelector('.review-slide-mobile.opacity-100');
            if (!activeSlide) {
                changeSlide('mobile-slide1', 'mobile-dot');
                activeSlide = document.getElementById('mobile-slide1');
            }
        }
        if (activeSlide) {
            updateContainerHeight(activeSlide);
        }
    }
    
    window.addEventListener('load', setContainerHeight);
    window.addEventListener('resize', setContainerHeight);

    setContainerHeight();

    let resizeTimeout;
    window.addEventListener('resize', function() {
        clearTimeout(resizeTimeout);
        resizeTimeout = setTimeout(setContainerHeight, 250);
    });
});
